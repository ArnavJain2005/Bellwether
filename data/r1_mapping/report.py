"""Deterministic R1 coverage report and missing-input manifest.

The report is generated only from committed files (sources, mapping, evidence,
candidates and the recorded SIG fixtures), so anyone can regenerate it without the
git-ignored venue output. It never describes R1 as G-1 completion.
"""

from __future__ import annotations

from collections import Counter
from typing import Any

from data.r1_mapping.common import VENUES
from data.r1_mapping.sig_inventory import InventoryAudit
from data.r1_mapping.validate import ValidationResult

G1_DISCLAIMER = (
    "R1 supplies classification evidence toward G-1. It does not pass G-1, does not "
    "decide commitment or related-market-group policy (OQ-C4), does not answer any "
    "section W question, and does not activate fair value or trading."
)


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    def cell(value: Any) -> str:
        return str(value).replace("|", "\\|")

    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return out


def missing_inputs(
    mapping: dict[str, Any],
    evidence: dict[str, Any],
    candidates: dict[str, Any] | None,
) -> list[dict[str, Any]]:
    """Per SIG contract, what is still needed before any decision can be verified."""
    evidence_by_id = {str(e.get("sig_market_id")): e for e in evidence.get("entries") or []}
    cand_by_id = {str(c["sig_market_id"]): c for c in (candidates or {}).get("contracts") or []}
    rows = []
    for record in mapping.get("records") or []:
        sig = record.get("sig") or {}
        mid = str(sig.get("market_id"))
        identity = record.get("identity") or {}
        needs = []
        if (evidence_by_id.get(mid) or {}).get("status") != "reviewed":
            needs.append("sig_info_tab_text")
        if identity.get("status") != "verified":
            needs.append("authoritative_race_identity")
        proposed = identity.get("proposed") or {}
        if proposed.get("election_type") in (None, "unverified") and proposed.get("office")                 not in ("senate_control", "house_control"):
            needs.append("election_type")
        cand = cand_by_id.get(mid)
        for venue in VENUES:
            decision = ((record.get("venues") or {}).get(venue) or {}).get("decision")
            if decision != "unresolved":
                continue
            if cand is None:
                needs.append(f"{venue}_candidate_scan")
            elif not cand[venue]["suggested"]:
                needs.append(f"{venue}_reviewed_listing")
            else:
                needs.append(f"{venue}_review")
        rows.append({
            "sig_market_id": mid,
            "sig_exchange_id": sig.get("exchange_id"),
            "title": sig.get("title"),
            "proposed_race_key": proposed.get("race_key"),
            "needs": needs,
        })
    return rows


def build_report(
    sources: dict[str, Any],
    mapping: dict[str, Any],
    evidence: dict[str, Any],
    candidates: dict[str, Any] | None,
    inventory: InventoryAudit,
    validation: ValidationResult,
) -> str:
    records = mapping.get("records") or []
    inv_src = sources.get("sig_inventory") or {}
    lines = [
        "# R1 coverage report",
        "",
        "Generated by `python -m data.r1_mapping report`. Do not edit by hand.",
        "",
        f"> **Not G-1 completion.** {G1_DISCLAIMER}",
        "",
        "## SIG inventory",
        "",
        (f"- Source: `{inv_src.get('run_dir')}` (`{inventory.source_id}`), captured "
        f"{inv_src.get('captured_at')}."),
        (f"- Cursor walk: {len(inventory.pages)} pages "
        f"({', '.join(str(p['items']) for p in inventory.pages)} items), reported total "
        f"{inventory.reported_total}; complete at capture time: "
        f"**{'yes' if inventory.complete else 'NO'}**."),
        (f"- Contracts (market + its single YES exchange): {len(inventory.contracts)}; "
        f"statuses {dict(Counter(c['status'] for c in inventory.contracts))}; categories "
        f"{dict(Counter('/'.join(c['categories']) for c in inventory.contracts))}."),
        ("- A complete walk at capture time is not proof of today's inventory. The pages carry "
        "no race ID, stage ID or Info-tab resolution text."),
        "",
    ]
    keys = Counter()
    offices = Counter()
    statuses = Counter()
    for r in records:
        identity = r.get("identity") or {}
        proposed = identity.get("proposed") or {}
        statuses[identity.get("status")] += 1
        if proposed.get("race_key"):
            if proposed["race_key"] not in keys:
                offices[proposed.get("office")] += 1
            keys[proposed["race_key"]] += 1
    settled_types = sum(
        1 for r in records
        if ((r.get("identity") or {}).get("proposed") or {}).get("election_type")
        not in (None, "unverified")
    )
    policies = sources.get("policies") or {}
    oq_status = (policies.get("oq_c4_related_market_groups") or {}).get("status")
    lines += [
        "## Race identity and groups",
        "",
        (f"- Race identities established from an authoritative source: "
        f"{statuses.get('verified', 0)} of {len(records)}."),
        (f"- Title-derived race-key **proposals**: {len(keys)} keys "
        f"({', '.join(f'{k} {v}' for k, v in sorted(offices.items()))}); contracts per key "
        f"{dict(sorted(Counter(keys.values()).items()))}. These are proposals, not race IDs."),
        f"- Election type (regular/special) settled: {settled_types} of {len(records)}.",
        (f"- OQ-C4 related-market groups: **{oq_status}**; contracts with an approved "
        f"group: {sum(1 for r in records if (r.get('groups') or {}).get('approved'))}."),
        "",
        "## SIG Info-tab resolution evidence",
        "",
    ]
    ev_status = Counter(e.get("status") for e in evidence.get("entries") or [])
    lines += [f"- {k}: {v}" for k, v in sorted(ev_status.items())]
    lines += ["", "## Venue decisions", ""]
    rows = []
    for venue in VENUES:
        counts = Counter(((r.get("venues") or {}).get(venue) or {}).get("decision")
                         for r in records)
        eligible = sum(1 for r in records
                       if ((r.get("venues") or {}).get(venue) or {}).get("fair_value_eligible"))
        pending = sum(1 for r in records
                      if (((r.get("venues") or {}).get(venue) or {}).get("review") or {})
                      .get("status") == "pending")
        rows.append([venue, counts.get("verified_match", 0),
                     counts.get("no_match_in_reviewed_scope", 0), counts.get("unresolved", 0),
                     pending, eligible])
    lines += _table(["venue", "verified_match", "no_match_in_reviewed_scope", "unresolved",
                     "pending review", "fair_value_eligible"], rows)
    lines += [""]
    for snap in sources.get("venue_snapshots") or []:
        val = snap.get("s1t5_validation") or {}
        lines += [
            (f"- Venue snapshot `{snap.get('id')}`: `{snap.get('file')}` (git-ignored, not "
            f"committed), sha256 `{snap.get('sha256')}`, fetched {snap.get('fetched_at')}, "
            f"Polymarket {snap.get('polymarket_count')}, Kalshi {snap.get('kalshi_count')}. "
            f"S1-T5 validator at `{str(val.get('code_sha'))[:12]}`: **{val.get('result')}**."),
        ]
        for venue in VENUES:
            cov = (snap.get("coverage") or {}).get(venue) or {}
            lines.append(f"  - {venue} coverage complete: {cov.get('complete')} "
                         f"({cov.get('basis')})")
    lines += ["", "## Candidate discovery (suggestions only)", ""]
    if candidates is None:
        lines.append("- No candidate file: run `candidates` with the frozen venue output.")
    else:
        gen = candidates.get("generated_from") or {}
        lines.append(f"- Generated from `{gen.get('venue_snapshot')}` "
                     f"(sha256 `{gen.get('venue_snapshot_sha256')}`).")
        lines.append("")
        crow = []
        for venue in VENUES:
            with_s = sum(1 for c in candidates["contracts"] if c[venue]["suggested"])
            multi = sum(1 for c in candidates["contracts"] if len(c[venue]["suggested"]) > 1)
            reasons = Counter()
            for c in candidates["contracts"]:
                reasons.update(c[venue]["near_miss_reason_counts"])
            top = ", ".join(f"{k} {v}" for k, v in reasons.most_common(6))
            crow.append([venue, with_s, len(candidates["contracts"]) - with_s, multi, top])
        lines += _table(["venue", "SIG contracts with a suggestion", "with none",
                         "with several", "most common near-miss reasons"], crow)
        shared = candidates.get("suggestions_shared_by_several_sig_contracts") or {}
        lines.append("")
        lines.append(f"- Venue outcomes suggested for more than one SIG contract: {len(shared)}.")
        flagged = Counter()
        for c in candidates["contracts"]:
            for venue in VENUES:
                for n in c[venue]["near_misses"]:
                    for reason in n["reasons"]:
                        if "conflicts" in reason or reason == "dfl_label_outside_minnesota":
                            flagged[(venue, n["id"], reason)] += 1
        if flagged:
            lines.append("- Venue metadata conflicts seen among near misses (fail closed, "
                         "never rewritten):")
            lines += [f"  - {v} `{i}`: {r}" for (v, i, r) in sorted(flagged)]
    lines += ["", "## Validation", ""]
    if validation.ok:
        lines.append("- Structural validation: **pass** (0 errors). Unresolved rows are not "
                     "errors; they are counted above.")
    else:
        lines.append(f"- Structural validation: **FAIL** ({len(validation.findings)} errors).")
        lines += [f"  - `{f.render()}`" for f in validation.findings[:50]]
    manifest = missing_inputs(mapping, evidence, candidates)
    needs = Counter(n for row in manifest for n in row["needs"])
    lines += [
        "",
        "## Missing-input manifest",
        "",
        "Counts of SIG contracts needing each input:",
        "",
    ]
    lines += [f"- `{k}`: {v}" for k, v in sorted(needs.items())]
    lines += [
        "",
        ("Inputs: `sig_info_tab_text` = verbatim SIG Info-tab resolution text for that market "
        "and exchange, captured and reviewed by an authorized person; "
        "`authoritative_race_identity` = a reviewed SIG race (and stage) identifier; "
        "`election_type` = regular or special, from that evidence; `<venue>_review` = a "
        "human decision on the suggested candidates; `<venue>_reviewed_listing` = a reviewed, "
        "complete venue listing for that race (the frozen snapshot is incomplete, so absence "
        "from it is not a no-match)."),
        "",
    ]
    lines += _table(
        ["SIG market", "exchange", "proposed race key", "needs"],
        [[r["sig_market_id"], r["sig_exchange_id"], r["proposed_race_key"],
          " ".join(r["needs"])] for r in manifest],
    )
    lines += ["", f"_{G1_DISCLAIMER}_", ""]
    return "\n".join(lines)
