"""Command line for the offline R1 workflow: ``python -m data.r1_mapping <command>``.

Commands:
  inventory   audit the declared SIG inventory (recorded fixture pages)
  init        write unresolved mapping and evidence skeletons (never overwrites)
  candidates  regenerate markets/r1_candidates.json from the frozen venue output
  validate    validate every committed R1 file; exit 1 on any structural error
  report      regenerate markets/R1_REPORT.md (--check: exit 1 if it is stale)

No command opens a network connection or reads secrets.
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from data.r1_mapping.candidates import dump_candidates, generate_candidates
from data.r1_mapping.common import (
    CANDIDATES_PATH,
    EVIDENCE_FORMAT,
    EVIDENCE_LAYOUT,
    EVIDENCE_PATH,
    MAPPING_FORMAT,
    MAPPING_LAYOUT,
    MAPPING_PATH,
    REPO_ROOT,
    REPORT_PATH,
    SOURCES_PATH,
    VENUES,
    Finding,
    dump_layout,
    load_json,
    rel,
    sha256_file,
    write_text,
)
from data.r1_mapping.identity import GROUP_PROPOSALS, proposed_group_ids, proposed_identity
from data.r1_mapping.report import build_report
from data.r1_mapping.sig_inventory import InventoryAudit, audit_inventory
from data.r1_mapping.validate import ValidationResult, snapshot_ids, validate_all

REASON_CODE_DEFINITIONS = {
    "sig_resolution_text_missing": (
        "SIG Info-tab resolution text for this market is not captured and reviewed, so the "
        "settlement condition, source and timing cannot be compared with any venue."),
    "sig_race_identity_unverified": (
        "No authoritative SIG race or stage ID is in reviewed inputs; the race key is a "
        "title-derived proposal, and regular versus special election is unknown."),
    "venue_snapshot_fails_current_s1t5_validation": (
        "The frozen venue output fails the S1-T5 validator on main, so its labels are not "
        "trusted and its contents are used for candidate discovery only."),
    "venue_coverage_incomplete": (
        "The frozen venue output does not cover the whole venue, so absence of a "
        "counterpart from it is unresolved, never a no-match."),
    "pending_reviewer_decision": (
        "No authorized reviewer has decided this pair; candidates in "
        "markets/r1_candidates.json are algorithmic suggestions only."),
}


def init_reason_codes(sources: dict[str, Any], snapshot_id: str) -> list[str]:
    codes = ["sig_resolution_text_missing", "sig_race_identity_unverified"]
    snap = snapshot_ids(sources).get(snapshot_id) or {}
    if (snap.get("s1t5_validation") or {}).get("result") != "pass":
        codes.append("venue_snapshot_fails_current_s1t5_validation")
    if not all(((snap.get("coverage") or {}).get(v) or {}).get("complete") for v in VENUES):
        codes.append("venue_coverage_incomplete")
    codes.append("pending_reviewer_decision")
    return codes


def build_skeletons(
    sources: dict[str, Any], inventory: InventoryAudit, snapshot_id: str, date: str
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Unresolved mapping and missing-evidence skeletons for every inventory contract."""
    codes = init_reason_codes(sources, snapshot_id)
    records = []
    entries = []
    for c in inventory.contracts:
        proposed = proposed_identity(c["title"])
        decision = {
            "decision": "unresolved",
            "reason_codes": codes,
            "venue_snapshot": snapshot_id,
            "match": None,
            "confidence": None,
            "discrepancies": [],
            "review": {"status": "pending", "reviewer": None, "reviewed_at": None},
            "fair_value_eligible": False,
        }
        records.append({
            "sig": {
                "market_id": c["market_id"],
                "exchange_id": c["exchange_id"],
                "option": c["option"],
                "title": c["title"],
                "settlement_date": c["settlement_date"],
            },
            "identity": {
                "status": "unresolved",
                "reason": "no authoritative SIG race ID or stage ID in reviewed inputs",
                "proposed": proposed,
                "authoritative": None,
            },
            "groups": {
                "status": "unresolved_oq_c4",
                "approved": [],
                "proposals": proposed_group_ids(proposed),
            },
            "venues": {venue: dict(decision) for venue in VENUES},
            "history": [{
                "at": date,
                "by": "Claude Code (R1 draft, not a review)",
                "change": "created",
                "detail": f"unresolved record generated by init from {inventory.source_id}",
            }],
        })
        entries.append({
            "sig_market_id": c["market_id"],
            "sig_exchange_id": c["exchange_id"],
            "status": "missing",
            "text_path": None,
            "text_sha256": None,
            "source": None,
            "captured_by": None,
            "captured_at": None,
            "reviewed_by": None,
            "reviewed_at": None,
        })
    mapping = {
        "format": MAPPING_FORMAT,
        "inventory_id": inventory.source_id,
        "reason_code_definitions": REASON_CODE_DEFINITIONS,
        "group_proposals": list(GROUP_PROPOSALS),
        "records": records,
    }
    evidence = {
        "format": EVIDENCE_FORMAT,
        "inventory_id": inventory.source_id,
        "instructions": (
            "One entry per SIG contract. Paste the verbatim Info-tab text into "
            "markets/sig_info_tab/<market_id>.md, set text_sha256 (LF-normalised SHA-256), "
            "source, captured_by and captured_at, and set status captured_unreviewed; an "
            "authorized reviewer then sets reviewed_by, reviewed_at and status reviewed."
        ),
        "entries": entries,
    }
    return mapping, evidence


def load_venue_snapshots(
    sources: dict[str, Any], mapping: dict[str, Any], explicit: list[Path], root: Path
) -> tuple[dict[str, dict[str, Any]], list[Finding]]:
    """Load the snapshots that verified decisions need (or that were passed explicitly).

    A file is used only when its SHA-256 equals the declared snapshot's hash.
    """
    declared = snapshot_ids(sources)
    needed = {
        ((r.get("venues") or {}).get(v) or {}).get("venue_snapshot")
        for r in mapping.get("records") or [] for v in VENUES
        if ((r.get("venues") or {}).get(v) or {}).get("decision") == "verified_match"
    }
    by_hash = {s.get("sha256"): sid for sid, s in declared.items()}
    loaded: dict[str, dict[str, Any]] = {}
    findings: list[Finding] = []
    for path in explicit:
        digest = sha256_file(path)
        sid = by_hash.get(digest)
        if sid is None:
            findings.append(Finding("venue_snapshot_hash_mismatch", rel(path, root),
                                    "file hash matches no declared venue snapshot"))
            continue
        loaded[sid] = load_json(path)
    for sid in sorted(n for n in needed if n and n not in loaded):
        path = root / str(declared.get(sid, {}).get("file") or "")
        if path.is_file():
            if sha256_file(path) == declared[sid].get("sha256"):
                loaded[sid] = load_json(path)
            else:
                findings.append(Finding("venue_snapshot_hash_mismatch", rel(path, root),
                                        f"local file is not snapshot {sid}"))
    return loaded, findings


def run_validation(root: Path, explicit: list[Path]) -> tuple[ValidationResult, dict[str, Any]]:
    markets = root / "markets"
    sources = load_json(markets / SOURCES_PATH.name)
    mapping = load_json(markets / MAPPING_PATH.name)
    evidence = load_json(markets / EVIDENCE_PATH.name)
    inventory = audit_inventory(sources.get("sig_inventory") or {}, root)
    snapshots, snap_findings = load_venue_snapshots(sources, mapping, explicit, root)
    result = validate_all(sources, mapping, evidence, inventory, snapshots, root)
    result.findings.extend(snap_findings)
    result.findings.sort()
    candidates_path = markets / CANDIDATES_PATH.name
    candidates = load_json(candidates_path) if candidates_path.is_file() else None
    return result, {"sources": sources, "mapping": mapping, "evidence": evidence,
                    "inventory": inventory, "candidates": candidates}


def render_report(root: Path) -> str:
    result, ctx = run_validation(root, [])
    return build_report(ctx["sources"], ctx["mapping"], ctx["evidence"], ctx["candidates"],
                        ctx["inventory"], result)


def main(argv: list[str] | None = None, root: Path = REPO_ROOT) -> int:
    parser = argparse.ArgumentParser(prog="python -m data.r1_mapping", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("inventory", help="audit the declared SIG inventory")
    p_init = sub.add_parser("init", help="write unresolved skeletons (never overwrites)")
    p_init.add_argument("--snapshot-id", required=True)
    p_init.add_argument("--date", default=datetime.now(UTC).strftime("%Y-%m-%d"))
    p_cand = sub.add_parser("candidates", help="regenerate the candidate report")
    p_cand.add_argument("--venue-snapshot", type=Path, required=True)
    p_cand.add_argument("--out", type=Path, default=None)
    p_val = sub.add_parser("validate", help="validate the committed R1 files")
    p_val.add_argument("--venue-snapshot", type=Path, action="append", default=[])
    p_rep = sub.add_parser("report", help="regenerate markets/R1_REPORT.md")
    p_rep.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    markets = root / "markets"

    if args.command == "inventory":
        sources = load_json(markets / SOURCES_PATH.name)
        audit = audit_inventory(sources.get("sig_inventory") or {}, root)
        print(f"inventory {audit.source_id}: {len(audit.pages)} pages, "
              f"{len(audit.contracts)} contracts, reported total {audit.reported_total}, "
              f"complete={audit.complete}")
        for page in audit.pages:
            print(f"  {page['file']}: {page['items']} items, hasMore={page['has_more']}, "
                  f"cursor_in={'yes' if page['request_cursor'] else 'none'}, "
                  f"next={'set' if page['next_cursor'] else 'null'}")
        for f in audit.findings:
            print(f.render())
        return 1 if audit.findings else 0

    if args.command == "init":
        sources = load_json(markets / SOURCES_PATH.name)
        if args.snapshot_id not in snapshot_ids(sources):
            print(f"unknown snapshot id {args.snapshot_id}", file=sys.stderr)
            return 2
        targets = (markets / MAPPING_PATH.name, markets / EVIDENCE_PATH.name)
        existing = [rel(t, root) for t in targets if t.exists()]
        if existing:
            print(f"refusing to overwrite reviewed files: {', '.join(existing)}",
                  file=sys.stderr)
            return 2
        audit = audit_inventory(sources.get("sig_inventory") or {}, root)
        if audit.findings or not audit.complete:
            for f in audit.findings:
                print(f.render(), file=sys.stderr)
            return 1
        mapping, evidence = build_skeletons(sources, audit, args.snapshot_id, args.date)
        write_text(targets[0], dump_layout(mapping, MAPPING_LAYOUT) + "\n")
        write_text(targets[1], dump_layout(evidence, EVIDENCE_LAYOUT) + "\n")
        print(f"wrote {len(mapping['records'])} records to {rel(targets[0], root)} and "
              f"{rel(targets[1], root)}")
        return 0

    if args.command == "candidates":
        sources = load_json(markets / SOURCES_PATH.name)
        digest = sha256_file(args.venue_snapshot)
        matches = [s for s in sources.get("venue_snapshots") or [] if s.get("sha256") == digest]
        if not matches:
            print(f"{args.venue_snapshot} (sha256 {digest}) is not a declared venue snapshot; "
                  "declare it in markets/r1_sources.json first", file=sys.stderr)
            return 2
        audit = audit_inventory(sources.get("sig_inventory") or {}, root)
        if audit.findings:
            for f in audit.findings:
                print(f.render(), file=sys.stderr)
            return 1
        snapshot = load_json(args.venue_snapshot)
        report = generate_candidates(audit.contracts, snapshot, matches[0], audit.source_id)
        out = args.out or markets / CANDIDATES_PATH.name
        write_text(out, dump_candidates(report))
        print(f"wrote candidates for {len(report['contracts'])} SIG contracts to {rel(out, root)}")
        return 0

    if args.command == "validate":
        result, ctx = run_validation(root, args.venue_snapshot)
        for f in result.findings:
            print(f.render())
        records = ctx["mapping"].get("records") or []
        for venue in VENUES:
            counts: dict[str, int] = {}
            for r in records:
                d = ((r.get("venues") or {}).get(venue) or {}).get("decision")
                counts[str(d)] = counts.get(str(d), 0) + 1
            print(f"{venue}: {dict(sorted(counts.items()))}")
        print(f"structural errors: {len(result.findings)}")
        return 0 if result.ok else 1

    text = render_report(root)
    path = markets / REPORT_PATH.name
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            print(f"{rel(path, root)} is stale; run: python -m data.r1_mapping report",
                  file=sys.stderr)
            return 1
        print(f"{rel(path, root)} is up to date")
        return 0
    write_text(path, text)
    print(f"wrote {rel(path, root)}")
    return 0
